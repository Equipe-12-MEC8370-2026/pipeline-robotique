"""CTA-SO101-ProfileStack-v0 (P3): lay the short profile flat in its zone, then stand the long profile on top.

Built from the CTA demo's TaskSpec through configs/tasks/so101_profile_stack.yaml (generated by
scripts/sim/make_so101_layout.py: D10 smaller parts, D11 short part starts lying). Same table, robot, cameras,
rates and action space as the P0 scene (CTA-SO101-PickPlace-v0, unchanged); no visual goal marker: the short
part's zone is fixed in front of the robot, the long part's goal follows the short part.
"""
from __future__ import annotations

import math

import isaaclab.envs.mdp as base_mdp
import isaaclab.sim as sim_utils
import yaml
from isaaclab.assets import AssetBaseCfg, RigidObjectCfg
from isaaclab.envs import ManagerBasedRLEnvCfg
from isaaclab.managers import EventTermCfg as EventTerm
from isaaclab.managers import ObservationGroupCfg as ObsGroup
from isaaclab.managers import ObservationTermCfg as ObsTerm
from isaaclab.managers import SceneEntityCfg
from isaaclab.managers import TerminationTermCfg as DoneTerm
from isaaclab.scene import InteractiveSceneCfg
from isaaclab.sensors import FrameTransformerCfg, TiledCameraCfg
from isaaclab.sensors.frame_transformer.frame_transformer_cfg import OffsetCfg
from isaaclab.utils import configclass
from isaaclab_physx.physics import PhysxCfg
from isaaclab_physx.sim.spawners.materials.physics_materials_cfg import RigidBodyMaterialCfg

from cta_learn import CONFIGS_DIR
from cta_learn.core.geometry import quat_from_euler_deg
from cta_learn.sim import mdp
from cta_learn.sim.tasks import pick_place as p0

TASK_ID = "CTA-SO101-ProfileStack-v0"
LAYOUT = yaml.safe_load((CONFIGS_DIR / "tasks" / "so101_profile_stack.yaml").read_text(encoding="utf-8"))
TASK_DESCRIPTION = LAYOUT["instruction"]["en"]
SHORT, LONG = LAYOUT["objects"]["profile_short"], LAYOUT["objects"]["profile_long"]
SECTION = SHORT["section_m"]
GOAL_SHORT_XY = tuple(LAYOUT["goals"]["profile_short"]["xyyaw"][:2])
# TCP for a 25 mm part: face 5 mm from the fixed finger (same rule as P0's 30 mm cube), 10 mm above the tips
TCP_OFFSET = (p0.FIXED_FINGER_INNER_X + 0.005 + SECTION / 2, 0.0, p0.FIXED_FINGER_TIP_Z + 0.010)
ALU = (0.78, 0.79, 0.82)  # aluminium-like grey
SUCCESS_HOLD_STEPS = 30   # the stack must stay complete and at rest for 1 s (30 env steps) to count
# P0 configs are dataclasses: reuse their entries through instances (P0 itself is not modified)
_P0_SCENE = p0.PickPlaceSceneCfg(num_envs=1, env_spacing=2.0)
_P0_EVENTS = p0.EventCfg()


def _range(o: dict, key: str = "range") -> dict:
    dx, dy, dyaw = o[key]
    return {"x": (-dx, dx), "y": (-dy, dy), "yaw": (-dyaw, dyaw)}


def _part(name: str, o: dict) -> RigidObjectCfg:
    x, y, yaw = o["start_xyyaw"]
    return RigidObjectCfg(
        prim_path="{ENV_REGEX_NS}/" + name,
        init_state=RigidObjectCfg.InitialStateCfg(pos=(x, y, o["size_m"][2] / 2 + 0.001),
                                                  rot=quat_from_euler_deg(0.0, 0.0, math.degrees(yaw))),
        spawn=sim_utils.CuboidCfg(
            size=tuple(o["size_m"]),
            rigid_props=sim_utils.RigidBodyPropertiesCfg(
                solver_position_iteration_count=16, solver_velocity_iteration_count=1, max_depenetration_velocity=1.0
            ),
            mass_props=sim_utils.MassPropertiesCfg(mass=o["mass_kg"]),
            collision_props=sim_utils.CollisionPropertiesCfg(),
            physics_material=RigidBodyMaterialCfg(static_friction=1.0, dynamic_friction=1.0),
            visual_material=sim_utils.PreviewSurfaceCfg(diffuse_color=ALU, metallic=0.6, roughness=0.35),
        ),
    )


@configclass
class ProfileStackSceneCfg(InteractiveSceneCfg):
    ground = _P0_SCENE.ground
    light = _P0_SCENE.light
    table = _P0_SCENE.table
    robot = _P0_SCENE.robot
    profile_short = _part("ProfileShort", SHORT)
    profile_long = _part("ProfileLong", LONG)
    ee_frame = FrameTransformerCfg(
        prim_path="{ENV_REGEX_NS}/Robot/base",
        debug_vis=False,
        target_frames=[  # look frames up by NAME (cta_learn.sim.mdp.frame_index): the transformer may reorder them
            FrameTransformerCfg.FrameCfg(prim_path="{ENV_REGEX_NS}/Robot/gripper", name="gripper"),
            FrameTransformerCfg.FrameCfg(prim_path="{ENV_REGEX_NS}/Robot/gripper", name="tcp", offset=OffsetCfg(pos=TCP_OFFSET)),
        ],
    )
    front = _P0_SCENE.front
    wrist = _P0_SCENE.wrist


_ROBOT_ORDERED = SceneEntityCfg("robot", joint_names=p0.JOINT_ORDER, preserve_order=True)


@configclass
class ObservationsCfg:
    @configclass
    class PolicyCfg(ObsGroup):
        joint_pos = ObsTerm(func=mdp.joint_pos_ordered, params={"asset_cfg": _ROBOT_ORDERED})
        front = ObsTerm(func=base_mdp.image, params={"sensor_cfg": SceneEntityCfg("front"), "data_type": "rgb", "normalize": False})
        wrist = ObsTerm(func=base_mdp.image, params={"sensor_cfg": SceneEntityCfg("wrist"), "data_type": "rgb", "normalize": False})

        def __post_init__(self):
            self.enable_corruption = False
            self.concatenate_terms = False

    @configclass
    class ExpertCfg(ObsGroup):
        """Privileged state for the scripted expert. Never given to a policy."""

        short_pos = ObsTerm(func=mdp.object_pos_env, params={"asset_cfg": SceneEntityCfg("profile_short")})
        short_quat = ObsTerm(func=mdp.object_quat, params={"asset_cfg": SceneEntityCfg("profile_short")})
        long_pos = ObsTerm(func=mdp.object_pos_env, params={"asset_cfg": SceneEntityCfg("profile_long")})
        long_quat = ObsTerm(func=mdp.object_quat, params={"asset_cfg": SceneEntityCfg("profile_long")})
        goal_short_xy = ObsTerm(func=mdp.goal_xy_const, params={"xy": GOAL_SHORT_XY})
        tcp_pos = ObsTerm(func=mdp.frame_pos_env, params={"frame_cfg": SceneEntityCfg("ee_frame"), "name": "tcp"})
        gripper_quat = ObsTerm(func=mdp.frame_quat, params={"frame_cfg": SceneEntityCfg("ee_frame"), "name": "gripper"})
        joint_pos = ObsTerm(func=mdp.joint_pos_ordered, params={"asset_cfg": _ROBOT_ORDERED})

        def __post_init__(self):
            self.enable_corruption = False
            self.concatenate_terms = False

    policy: PolicyCfg = PolicyCfg()
    expert: ExpertCfg = ExpertCfg()


@configclass
class EventCfg:
    # robot only: the parts are placed once, by their own events (no double teleport, see mdp)
    reset_robot = EventTerm(func=mdp.reset_articulations_to_default, mode="reset")
    profile_short = EventTerm(func=base_mdp.reset_root_state_uniform, mode="reset",
                              params={"pose_range": _range(SHORT), "velocity_range": {}, "asset_cfg": SceneEntityCfg("profile_short")})
    profile_long = EventTerm(func=base_mdp.reset_root_state_uniform, mode="reset",
                             params={"pose_range": _range(LONG), "velocity_range": {}, "asset_cfg": SceneEntityCfg("profile_long")})
    # must stay AFTER the two placement events: otherwise PhysX drags the parts back toward their previous pose
    forget_contacts = EventTerm(func=mdp.break_rigid_contacts, mode="reset",
                                params={"asset_names": ("profile_short", "profile_long")})
    light = _P0_EVENTS.light
    # table kept at most mid-grey so the aluminium parts stay visible against it
    table_color = EventTerm(func=mdp.randomize_shader_color, mode="reset",
                            params={"prim_suffix": "Table", "color_low": (0.22, 0.22, 0.22), "color_high": (0.52, 0.50, 0.48)})
    front_camera = _P0_EVENTS.front_camera


@configclass
class TerminationsCfg:
    time_out = DoneTerm(func=base_mdp.time_out, time_out=True)
    success = DoneTerm(func=mdp.profile_stack_success,
                       params={"short_cfg": SceneEntityCfg("profile_short"), "long_cfg": SceneEntityCfg("profile_long"),
                               "ee_frame_cfg": SceneEntityCfg("ee_frame"), "layout": LAYOUT,
                               "hold_steps": SUCCESS_HOLD_STEPS})
    short_dropped = DoneTerm(func=mdp.object_off_table, params={"object_cfg": SceneEntityCfg("profile_short")})
    long_dropped = DoneTerm(func=mdp.object_off_table, params={"object_cfg": SceneEntityCfg("profile_long")})


@configclass
class RewardsCfg:
    """No rewards: imitation learning and evaluation only."""


@configclass
class ProfileStackEnvCfg(ManagerBasedRLEnvCfg):
    scene: ProfileStackSceneCfg = ProfileStackSceneCfg(num_envs=1, env_spacing=2.0, replicate_physics=False)
    observations: ObservationsCfg = ObservationsCfg()
    actions: p0.ActionsCfg = p0.ActionsCfg()
    events: EventCfg = EventCfg()
    terminations: TerminationsCfg = TerminationsCfg()
    rewards: RewardsCfg = RewardsCfg()

    task_description: str = TASK_DESCRIPTION

    def use_ood_ranges(self) -> None:
        """Out-of-range evaluation trials: wider start ranges (P3.5)."""
        self.events.profile_short.params["pose_range"] = _range(SHORT, "range_ood")
        self.events.profile_long.params["pose_range"] = _range(LONG, "range_ood")

    def __post_init__(self) -> None:
        self.decimation = 2
        self.episode_length_s = 40.0   # two pick-and-places (P0: 20 s for one)
        self.sim.dt = 1.0 / 60.0
        self.sim.render_interval = self.decimation
        self.sim.render.rendering_mode = "balanced"
        self.sim.physics = PhysxCfg(bounce_threshold_velocity=0.01, friction_correlation_distance=0.00625)
        self.viewer.eye = (0.75, -0.55, 0.55)
        self.viewer.lookat = (0.15, 0.0, 0.0)
