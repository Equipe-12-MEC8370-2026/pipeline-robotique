r"""D12 trial: demo video of the Isaac Lab Mimic experiment (any Python with ffmpeg on PATH).

    .\.venv-learn\Scripts\python.exe scripts\eval\make_mimic_trial_video.py --out outputs\p3_mimic\demo_mimic_trial.mp4

Parts: title | 3 demos generated by Mimic (front | wrist) | the same evaluation trials played by ACT trained on the
500 expert demos (left) and by ACT trained on the 195 Mimic demos (right) | a success of ACT-Mimic | results card.
Clips are sped up (--speed) to keep the video short; captions say so.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_montage import FONT, FPS, H, W, _esc, card  # noqa: E402

FR = {"success": "réussi", "long_fell": "profilé long tombé", "long_never_lifted": "profilé long jamais saisi",
      "short_not_placed": "bout court hors zone", "long_not_on_short": "long décalé sur le court",
      "short_never_lifted": "bout court jamais saisi", "stack_not_released": "pile non relâchée"}


def label(text, x, y, size=20, color="white"):
    return (f"drawtext=fontfile='{FONT}':expansion=none:text='{_esc(text)}':x={x}:y={y}:fontsize={size}:fontcolor={color}"
            f":box=1:boxcolor=black@0.6:boxborderw=6")


def run(args_list):
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", *args_list], check=True)


def enc(dst):
    return ["-c:v", "libx264", "-crf", "20", "-pix_fmt", "yuv420p", "-r", str(FPS), "-an", str(dst)]


def generated_clip(ep: Path, caption: str, speed: float, dst: Path) -> None:
    f = (f"[0:v][1:v]hstack=inputs=2,setpts=PTS/{speed},scale={W}:{H},{label(caption, '10', '10')},"
         f"{label(f'accéléré x{speed:g}', 'w-text_w-10', 'h-40', 18, 'yellow')}[v]")
    run(["-i", str(ep / "front.mp4"), "-i", str(ep / "wrist.mp4"), "-filter_complex", f, "-map", "[v]", *enc(dst)])


def compare_clip(left: Path, right: Path, l_txt: str, r_txt: str, bottom: str, speed: float, dst: Path) -> None:
    # eval videos are front | wrist (1280x480): keep the front view of each, side by side; the shorter one freezes
    f = (f"[0:v]crop=640:480:0:0,setpts=PTS/{speed},tpad=stop_mode=clone:stop_duration=30,{label(l_txt, '10', '10', 18)}[l];"
         f"[1:v]crop=640:480:0:0,setpts=PTS/{speed},tpad=stop_mode=clone:stop_duration=30,{label(r_txt, '10', '10', 18)}[r];"
         f"[l][r]hstack=inputs=2,{label(bottom, '(w-text_w)/2', 'h-40', 20, 'yellow')}[v]")
    dur = max(_duration(left), _duration(right)) / speed + 1.0
    run(["-i", str(left), "-i", str(right), "-filter_complex", f, "-map", "[v]", "-t", f"{dur:.2f}", *enc(dst)])


def single_clip(video: Path, caption: str, speed: float, dst: Path) -> None:
    f = f"[0:v]setpts=PTS/{speed},{label(caption, '10', '10')},{label(f'accéléré x{speed:g}', 'w-text_w-10', 'h-40', 18, 'yellow')}[v]"
    run(["-i", str(video), "-filter_complex", f, "-map", "[v]", *enc(dst)])


def _duration(p: Path) -> float:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)],
                         capture_output=True, text=True, check=True).stdout
    return float(out.strip())


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--raw", default="data/raw/p3_mimic")
    p.add_argument("--episodes", type=int, nargs="+", default=[0, 60, 120])
    p.add_argument("--act", default="outputs/p3_5/act_p3_n25")
    p.add_argument("--mimic", default="outputs/p3_5/act_p3_mimic_n25")
    p.add_argument("--compare", type=int, nargs="+", default=[0, 1])
    p.add_argument("--mimic_success", type=int, default=5)
    p.add_argument("--speed", type=float, default=2.0)
    p.add_argument("--out", default="outputs/p3_mimic/demo_mimic_trial.mp4")
    a = p.parse_args()
    import json
    out_m = {r["trial"]: r["outcome"] for r in json.loads((Path(a.mimic) / "report.json").read_text())["records"]}
    out_a = {r["trial"]: r["outcome"] for r in json.loads((Path(a.act) / "report.json").read_text())["records"]}
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        parts = []

        def add_card(lines, s=4.5):
            parts.append(tmp / f"card_{len(parts)}.mp4")
            card(lines, s, parts[-1])

        add_card(["Projet CTA : générer les démonstrations sans expert codé à la main",
                  "Isaac Lab Mimic : quelques démos de référence -> des centaines de démos, sans code propre à la tâche",
                  "Tâche : poser le bout de profilé court à plat, puis le profilé long debout dessus (SO-101, simulation)"], 6)
        add_card(["1. Démos générées automatiquement",
                  "10 démos de référence -> 200 démos en 322 tentatives (62 %), dont 195 gardées après rendu",
                  "avec une seule démo de référence : 52,5 % des tentatives réussissent"])
        for k, ep in enumerate(a.episodes):
            parts.append(tmp / f"gen_{k}.mp4")
            generated_clip(Path(a.raw) / f"episode_{ep:06d}", f"Démo générée par Mimic n° {ep} (vue avant | vue poignet)",
                           a.speed, parts[-1])
        add_card(["2. Même essai d'évaluation, deux politiques ACT",
                  "à gauche : ACT entraîné sur 500 démos de l'expert codé (44/50)",
                  "à droite : ACT entraîné sur les 195 démos Mimic (14/50)"])
        for t in a.compare:
            parts.append(tmp / f"cmp_{t}.mp4")
            compare_clip(Path(a.act) / "videos" / f"trial_{t:03d}.mp4", Path(a.mimic) / "videos" / f"trial_{t:03d}.mp4",
                         f"ACT, démos d'expert : {FR.get(out_a[t], out_a[t])}", f"ACT, démos Mimic : {FR.get(out_m[t], out_m[t])}",
                         f"Essai {t} (mêmes conditions de départ) - accéléré x{a.speed:g}", a.speed, parts[-1])
        add_card(["3. Une réussite d'ACT entraîné sur les démos Mimic"], 3)
        t = a.mimic_success
        parts.append(tmp / "mimic_ok.mp4")
        single_clip(Path(a.mimic) / "videos" / f"trial_{t:03d}.mp4", f"ACT, démos Mimic - essai {t} : réussi (vue avant | vue poignet)",
                    a.speed, parts[-1])
        add_card(["Bilan de la nuit",
                  "La génération automatique fonctionne : aucun code propre à la tâche, 52,5 % de réussite dès 1 démo de référence",
                  "Mais ACT entraîné sur ces démos : 14/50 (contre 44/50 avec l'expert)",
                  "Cause identifiée : bruit ajouté à chaque pas -> mouvements 8x plus saccadés",
                  "Suite : régénérer sans bruit, réentraîner, réévaluer"], 7)
        lst = tmp / "list.txt"
        lst.write_text("".join(f"file '{q.as_posix()}'\n" for q in parts), encoding="utf-8")
        out = Path(a.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        run(["-f", "concat", "-safe", "0", "-i", str(lst), "-c", "copy", str(out)])
    print(f"-> {out} ({_duration(out):.0f} s)")


if __name__ == "__main__":
    main()
