"""P3.1 — write the SO-101 scene layout of the profile task from its TaskSpec (D10 sizes, D11 start postures).

    .venv-learn\\Scripts\\python.exe scripts\\sim\\make_so101_layout.py
-> configs/tasks/so101_profile_stack.yaml (committed; read by cta_learn.sim.tasks.profile_stack in isaacsim-env)
"""
from __future__ import annotations

import yaml

from cta_learn import CONFIGS_DIR
from cta_learn.core.taskspec import TaskSpec
from cta_learn.retarget.profile_stack import so101_layout

SPEC = CONFIGS_DIR / "taskspecs" / "cta_profile_upright_113656.json"
DST = CONFIGS_DIR / "tasks" / "so101_profile_stack.yaml"


def main() -> None:
    lay = so101_layout(TaskSpec.load(SPEC))
    header = ("# GENERATED by scripts/sim/make_so101_layout.py from configs/taskspecs/cta_profile_upright_113656.json\n"
              "# (cta_learn.retarget.profile_stack). Do not edit by hand: change the generator or its defaults.\n")
    DST.write_text(header + yaml.safe_dump(lay, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"[layout] -> {DST}")
    for d in lay["deviations"]:
        print(f"   {d}")


if __name__ == "__main__":
    main()
