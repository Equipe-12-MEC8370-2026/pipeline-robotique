r"""Write the SO-101 scene layout of any TaskSpec + its adaptation config (generic, cta_learn.retarget.layout).

    .venv-learn\Scripts\python.exe scripts\sim\make_robot_layout.py --taskspec configs/taskspecs/cta_angle_block_114110.json
        [--adapt configs/tasks/so101_adapt_cta_angle_block.yaml]
-> configs/tasks/so101_<task_id>.yaml (committed; read by cta_learn.sim.tasks.taskspec_task in isaacsim-env)
"""
from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from cta_learn import CONFIGS_DIR, REPO_ROOT
from cta_learn.core.taskspec import TaskSpec
from cta_learn.retarget.layout import robot_layout


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--taskspec", type=Path, required=True)
    ap.add_argument("--adapt", type=Path, default=None, help="default configs/tasks/so101_adapt_<task_id>.yaml if it exists")
    a = ap.parse_args()
    spec = TaskSpec.load(a.taskspec)
    adapt_path = a.adapt or CONFIGS_DIR / "tasks" / f"so101_adapt_{spec.task_id}.yaml"
    adapt = yaml.safe_load(adapt_path.read_text(encoding="utf-8")) if adapt_path.exists() else {}
    lay = robot_layout(spec, adapt)
    dst = CONFIGS_DIR / "tasks" / f"so101_{spec.task_id}.yaml"
    rel = lambda p: Path(p).resolve().relative_to(REPO_ROOT.resolve()).as_posix()
    header = (f"# GENERATED by scripts/sim/make_robot_layout.py from {rel(a.taskspec)}\n"
              f"# + {rel(adapt_path) if adapt_path.exists() else 'the defaults'} (cta_learn.retarget.layout). Do not edit by hand.\n")
    dst.write_text(header + yaml.safe_dump(lay, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"[layout] -> {dst}")
    for d in lay["deviations"]:
        print(f"   {d}")


if __name__ == "__main__":
    main()
